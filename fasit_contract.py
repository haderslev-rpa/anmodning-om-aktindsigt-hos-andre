"""Midlertidig kontrakt til de q-fasit-funktioner, som implementeres separat."""
from typing import Any, Protocol
from models import BinaryFile

class FasitGateway(Protocol):
    async def find_citizen_id(self, *, cpr: str) -> str: ...
    async def find_case(self, *, citizen_id: str, case_number: str) -> dict[str, Any]: ...
    async def save_document(self, *, citizen_id: str, case_id: str, document: BinaryFile, title: str, category: str) -> dict[str, Any]: ...
    async def send_authority_letter(self, *, citizen_id: str, case_id: str, p_number: str, institution_name: str, letter: BinaryFile, attachments: list[BinaryFile], letter_type: str) -> dict[str, Any]: ...
    async def create_caseworker_task(self, *, citizen_id: str, case_id: str, due_date: str, title: str, description: str, category_id: str, responsible_case_worker_id: str, responsible_team_id: str, case_type: str, task_status: str) -> dict[str, Any]: ...
